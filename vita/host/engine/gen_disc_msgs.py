#!/usr/bin/env python3
"""gen_disc_msgs.py -- render the "bring your own disc" error screens (2026-10-27) as 1-bit 960x544 bitmaps -> src/stfx_disc_msgs.h.
The Vita shows one with sceDisplaySetFrameBuf before anything else is up (vita_tool_main.c), when stfx_retail_load refuses the image.
Index = STFX_DISC_* (dvd_shim.h): 1 missing, 2 wrong game, 3 wrong revision / modified, 4 unreadable.

    python gen_disc_msgs.py        # rewrites ../../src/stfx_disc_msgs.h
"""
import os
from PIL import Image, ImageDraw, ImageFont

W, H = 960, 544
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'src', 'stfx_disc_msgs.h')
HEAD = 'Star Fox Adventures - PS Vita fan port'
FOOT = ['This port contains no game data: it runs from your own copy.', 'Press the PS button to close the app.']
WHERE = ['Put a 1:1 dump of your own disc, as a full .iso (about 1.4 GB), at:', '    ux0:data/stairfax/sfa_rev1.iso']
MSGS = {
    1: ('No game disc image found.', WHERE + ['', 'It must be Star Fox Adventures, USA, Rev 1 (GSAE01, version 1).']),
    2: ('This disc image is a different game.', ['The file at ux0:data/stairfax/sfa_rev1.iso is not', 'Star Fox Adventures, USA (game id GSAE01).', ''] + WHERE),
    3: ('This disc image is the wrong revision, or modified.', ['This port needs the USA Rev 1 disc (GSAE01, version 1), unmodified.',
        'RVZ / GCZ / CISO images: convert to ISO with Dolphin (Convert File).', 'NKit images: restore them to a full ISO first.', ''] + WHERE),
    4: ('The disc image could not be read.', ['It is truncated or not a GameCube disc image.', 'Dump or convert it again to a full .iso.', ''] + WHERE),
}


def font(sz, bold=False):
    for n in (['segoeuib.ttf', 'arialbd.ttf'] if bold else ['segoeui.ttf', 'arial.ttf']):
        try: return ImageFont.truetype('C:/Windows/Fonts/' + n, sz)
        except OSError: pass
    return ImageFont.load_default()


def render(title, body):
    im = Image.new('1', (W, H), 0); d = ImageDraw.Draw(im)
    d.text((48, 40), HEAD, font=font(26), fill=1)
    d.line((48, 84, W - 48, 84), fill=1, width=2)
    d.text((48, 112), title, font=font(34, True), fill=1)
    y = 180
    for line in body: d.text((48, y), line, font=font(24), fill=1); y += 36
    y = H - 100
    for line in FOOT: d.text((48, y), line, font=font(22), fill=1); y += 34
    return im


def main():
    out = ['/* GENERATED by host/engine/gen_disc_msgs.py -- do not edit. 1-bit 960x544 error screens, MSB first, a row = 120 bytes.',
           ' * stfx_disc_msg[i] for STFX_DISC_* i = 1..4 (dvd_shim.h); [0] is unused. */',
           '#pragma once', f'#define STFX_DISC_MSG_W {W}', f'#define STFX_DISC_MSG_H {H}']
    for i in sorted(MSGS):
        b = render(*MSGS[i]).tobytes()
        assert len(b) == W * H // 8
        out.append(f'static const unsigned char stfx_disc_msg_{i}[{len(b)}] = {{')
        for k in range(0, len(b), 40): out.append('  ' + ','.join(str(x) for x in b[k:k + 40]) + ',')
        out.append('};')
        render(*MSGS[i]).save(os.path.join(HERE, f'disc_msg_{i}.png'))
    out.append('static const unsigned char *const stfx_disc_msg[5] = { 0, stfx_disc_msg_1, stfx_disc_msg_2, stfx_disc_msg_3, stfx_disc_msg_4 };')
    open(OUT, 'w', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', OUT, os.path.getsize(OUT), 'bytes; previews disc_msg_*.png')


main()
